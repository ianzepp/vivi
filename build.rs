//! Embed every file under `skills/` so the binary's skill text matches its version.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

fn main() -> io::Result<()> {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let skills_dir = manifest.join("skills");
    println!("cargo:rerun-if-changed=skills");

    let mut files = Vec::new();
    collect_files(&skills_dir, &skills_dir, &mut files)?;
    files.sort();
    if files.is_empty() {
        return Err(io::Error::other("skills/ is empty; nothing to embed"));
    }

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("embedded_skills.rs");
    let mut body = String::from(
        "// Generated by build.rs. Do not edit.\n\
         static EMBEDDED_FILES: &[(&str, &str)] = &[\n",
    );
    for rel in &files {
        println!("cargo:rerun-if-changed=skills/{rel}");
        writeln!(
            body,
            "    ({rel:?}, include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/skills/{rel}\"))),",
        )
        .expect("write generated catalog line");
    }
    body.push_str("];\n");
    fs::write(out, body)?;
    Ok(())
}

fn collect_files(root: &Path, dir: &Path, files: &mut Vec<String>) -> io::Result<()> {
    let mut entries = fs::read_dir(dir)?.collect::<Result<Vec<_>, _>>()?;
    entries.sort_by_key(fs::DirEntry::file_name);
    for entry in entries {
        let path = entry.path();
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            collect_files(root, &path, files)?;
            continue;
        }
        if path.is_file() {
            let rel = path.strip_prefix(root).map_err(io::Error::other)?;
            files.push(rel.to_string_lossy().replace('\\', "/"));
        }
    }
    Ok(())
}
