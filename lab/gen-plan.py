#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate a lab scenario: its plan.toml and its repository.

    gen-plan.py <name> --units N [--machines M] [--slots S] [--agent-secs T]
                [--task-fail-pct P] [--need-fail-pct P] [--stages STAGE=BOOL ...]

Writes lab/scenarios/<name>/plan.toml (one need, N independent units, each a
new file src/u<k>.sh) and copies the shared lab repository beside it. The
world (machines and slots per machine) rides in the plan's [world] table,
which up.sh and the hub's setup read.
"""
import argparse
import shutil
from pathlib import Path

LAB = Path(__file__).resolve().parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("--units", type=int, required=True)
    ap.add_argument("--machines", type=int, default=1)
    ap.add_argument("--slots", type=int, default=4)
    ap.add_argument("--agent-secs", type=float, default=0.0)
    ap.add_argument("--task-fail-pct", type=float, default=0.0)
    ap.add_argument("--need-fail-pct", type=float, default=0.0)
    ap.add_argument("--stages", nargs="*", default=[], metavar="STAGE=BOOL",
                    help="[pump.flow.stages] switches, e.g. audit=false judge=false")
    args = ap.parse_args()

    out = LAB / "scenarios" / args.name
    out.mkdir(parents=True, exist_ok=True)
    repo = out / "repo"
    if repo.exists():
        shutil.rmtree(repo)
    shutil.copytree(LAB / "scenarios" / "micro" / "repo", repo)

    n = args.units
    lines = [
        f"# Generated by gen-plan.py: one need, {n} independent units,",
        f"# {args.machines} machine(s) x {args.slots} slot(s).",
        'target = "app"',
        "",
        "[world]",
        f"machines = {args.machines}",
        f"slots = {args.slots}",
        f"agent_secs = {args.agent_secs}",
        f"task_fail_pct = {args.task_fail_pct}",
        f"need_fail_pct = {args.need_fail_pct}",
        "stages = {" + ", ".join(f"{k} = {v.lower()}" for k, v in (x.split("=") for x in args.stages)) + "}",
        "",
        "[need]",
        f'subject = "lab {args.name}: add {n} units"',
        f'done_when = ["src/u1.sh to src/u{n}.sh exist and ./check.sh passes"]',
        f'body = "Add {n} units, u1 to u{n}. Each is src/<unit>.sh defining a function named after the file that prints its own name."',
        "",
    ]
    for k in range(1, n + 1):
        u = f"u{k}"
        lines += [
            "[[slice]]",
            f'id = "{u}"',
            f'title = "Add unit {u}"',
            f'brief = "Create src/{u}.sh.\\nLAB-EDIT: src/{u}.sh {u}() {{ echo {u}; }}"',
            f'write_scope = ["src/{u}.sh"]',
            "",
        ]
    (out / "plan.toml").write_text("\n".join(lines))
    print(f"wrote {out / 'plan.toml'}: {n} units, {args.machines}x{args.slots} slots")


if __name__ == "__main__":
    main()
