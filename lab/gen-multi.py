#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate a multi-need lab scenario: several needs, each with slices whose
dependencies form a random graph.

    gen-multi.py <name> [--seed N] [--needs MIN MAX] [--slices MIN MAX]
                 [--machines M] [--slots S] [--agent-secs T]
                 [--task-fail-pct P] [--need-fail-pct P] [--stages STAGE=BOOL ...]
                 [--misbehave NAME=PCT ...] [--cto-answer A] [--rework-strict]
                 [--conflict-pct P] [--main-fail-pct P]

Writes lab/scenarios/<name>/plan.toml and copies the shared lab repository.
Each need is a `[[need]]` table with its own `[[need.slice]]` list. Every
slice adds one unit file, src/<need><unit>.sh, so needs never touch the same
file and their merges to main never conflict. A need's body carries a
`LAB-NEED: <id>` line; the stand-in planner copies it into the plan, which is
how the stand-in slicer knows which need it is slicing.

Dependency frequencies, per slice after a need's first:
- 35% no dependency (a root);
- 50% one dependency, 15% two;
- each dependency is one of the three slices just before it 70% of the time
  (chains), otherwise any earlier slice (fan-in from older work).
"""
import argparse
import random
import shutil
from pathlib import Path

LAB = Path(__file__).resolve().parent
P_ROOT, P_ONE = 0.35, 0.50  # the rest: two dependencies
P_RECENT, RECENT = 0.70, 3


def deps_for(k, rng):
    """Dependencies of slice k (0-based) on earlier slices of its need."""
    if k == 0:
        return []
    roll = rng.random()
    if roll < P_ROOT:
        return []
    want = 1 if roll < P_ROOT + P_ONE else 2
    picked = set()
    while len(picked) < min(want, k):
        if rng.random() < P_RECENT:
            picked.add(rng.randrange(max(0, k - RECENT), k))
        else:
            picked.add(rng.randrange(0, k))
    return sorted(picked)


def depth(deps):
    """Longest dependency chain, in slices."""
    memo = {}
    def d(i):
        if i not in memo:
            memo[i] = 1 + max((d(j) for j in deps[i]), default=0)
        return memo[i]
    return max(d(i) for i in range(len(deps)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--needs", type=int, nargs=2, default=[5, 10], metavar=("MIN", "MAX"))
    ap.add_argument("--slices", type=int, nargs=2, default=[6, 14], metavar=("MIN", "MAX"))
    ap.add_argument("--machines", type=int, default=2)
    ap.add_argument("--slots", type=int, default=5)
    ap.add_argument("--agent-secs", type=float, default=0.0)
    ap.add_argument("--task-fail-pct", type=float, default=0.0)
    ap.add_argument("--need-fail-pct", type=float, default=0.0)
    ap.add_argument("--stages", nargs="*", default=[], metavar="STAGE=BOOL")
    # Stand-in misbehaviors at random rates (sim-agent's [world.misbehave]).
    ap.add_argument("--misbehave", nargs="*", default=[], metavar="NAME=PCT")
    ap.add_argument("--cto-answer", default="rework")
    ap.add_argument("--rework-strict", action="store_true")
    # Percent of slices that also write their need's shared notes file outside
    # their scope: parallel slices of one need then conflict at the merge.
    ap.add_argument("--conflict-pct", type=float, default=0.0)
    ap.add_argument("--main-fail-pct", type=float, default=0.0)
    args = ap.parse_args()
    rng = random.Random(args.seed)

    out = LAB / "scenarios" / args.name
    out.mkdir(parents=True, exist_ok=True)
    repo = out / "repo"
    if repo.exists():
        shutil.rmtree(repo)
    shutil.copytree(LAB / "scenarios" / "micro" / "repo", repo)

    n_needs = rng.randint(*args.needs)
    stages = ", ".join(f"{k} = {v.lower()}" for k, v in (x.split("=") for x in args.stages))
    lines = [
        f"# Generated by gen-multi.py (seed {args.seed}): {n_needs} needs with random",
        f"# slice dependencies, {args.machines} machine(s) x {args.slots} slot(s).",
        'target = "app"',
        "",
        "[world]",
        f"machines = {args.machines}",
        f"slots = {args.slots}",
        f"agent_secs = {args.agent_secs}",
        f"task_fail_pct = {args.task_fail_pct}",
        f"need_fail_pct = {args.need_fail_pct}",
        f"main_fail_pct = {args.main_fail_pct}",
        f'cto_answer = "{args.cto_answer}"',
        f"rework_strict = {'true' if args.rework_strict else 'false'}",
        f"stages = {{{stages}}}",
        "",
    ]
    if args.misbehave:
        lines += ["[world.misbehave]"] + [f"{k} = {float(v)}" for k, v in (x.split("=") for x in args.misbehave)] + [""]
    total, summary = 0, []
    for n in range(1, n_needs + 1):
        need = f"n{n}"
        count = rng.randint(*args.slices)
        deps = [deps_for(k, rng) for k in range(count)]
        total += count
        roots = sum(1 for d in deps if not d)
        summary.append(f"{need}: {count} slices, {roots} roots, longest chain {depth(deps)}")
        lines += [
            "[[need]]",
            f'id = "{need}"',
            f'subject = "lab {args.name} {need}: add {count} units"',
            f'done_when = ["src/{need}u1.sh to src/{need}u{count}.sh exist and ./check.sh passes"]',
            f'body = "LAB-NEED: {need}\\nAdd {count} units, {need}u1 to {need}u{count}."',
            "",
        ]
        for k in range(count):
            u = f"{need}u{k + 1}"
            dep_ids = ", ".join(f'"{need}u{j + 1}"' for j in deps[k])
            shared = (f"\\nLAB-EDIT: notes/{need}-shared.txt {u}"
                      if rng.random() * 100 < args.conflict_pct else "")
            lines += [
                "[[need.slice]]",
                f'id = "{u}"',
                f'title = "Add unit {u}"',
                f'brief = "Create src/{u}.sh.\\nLAB-EDIT: src/{u}.sh {u}() {{ echo {u}; }}{shared}"',
                f'write_scope = ["src/{u}.sh"]',
                f"deps = [{dep_ids}]",
                "",
            ]
    (out / "plan.toml").write_text("\n".join(lines))
    print(f"wrote {out / 'plan.toml'}: {n_needs} needs, {total} slices")
    for line in summary:
        print(f"  {line}")


if __name__ == "__main__":
    main()
